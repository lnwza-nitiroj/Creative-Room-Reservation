    private void updateTimeSlotStatus(JButton button, int row, int currentDay, SheetsQuickstart sqs) {
        try {
            java.util.List<java.util.List<Object>> data = sqs.readData("room" + name + "!B" + row + ":D" + row);

            if (data != null && !data.isEmpty() && data.get(0).size() >= 3) {
                String status = data.get(0).get(0).toString();
                int bookingDate = Integer.parseInt(data.get(0).get(1).toString());
                String userId = data.get(0).get(2).toString();

                if (status.equalsIgnoreCase("used") && bookingDate == currentDay) {
                    button.setBackground(new Color(249, 102, 102));
                    button.setToolTipText("Booked by: " + userId);
                } else {
                    button.setBackground(new Color(119, 255, 119));
                    button.setToolTipText("Available");
                }
            } else {
                button.setBackground(new Color(119, 255, 119));
                button.setToolTipText("Available");
            }
        } catch (Exception e) {
            button.setBackground(Color.YELLOW);
            button.setForeground(Color.BLACK);
            button.setToolTipText("Error checking status");
        }
    }

