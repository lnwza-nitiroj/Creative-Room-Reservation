    public void booking(int timeSlotIndex, int rowToUpdate) {
        try {
            // 1. ตรวจสอบค่าอินพุต
            if (timeSlotIndex < 0 || timeSlotIndex > 9) { // มี 10 ช่วงเวลา (0-9)
                JOptionPane.showMessageDialog(null, "Invalid time slot selected", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 2. อ่านข้อมูลการจองจาก Google Sheets
            databook = Login.sqs.readData("room" + name + "!B2:D11");

            if (databook == null || databook.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Failed to load booking data", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 3. ตรวจสอบว่าช่วงเวลานี้ว่างหรือไม่
            java.util.List<Object> timeSlotData = databook.get(timeSlotIndex);
            if (timeSlotData == null || timeSlotData.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Time slot data not found", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            String status = timeSlotData.get(0).toString();
            String bookingDate = timeSlotData.size() > 1 ? timeSlotData.get(1).toString() : "";
            String bookedBy = timeSlotData.size() > 2 ? timeSlotData.get(2).toString() : "";

            // 4. ตรวจสอบสถานะการจอง
            if ("no".equalsIgnoreCase(status) || status.isEmpty()) {
                // 5. จองห้อง
                String currentDate = date.getCurrentDayofyear();
                String currentUser = Login.currentUser;

                java.util.List<java.util.List<Object>> usedData = Arrays.asList(
                        Arrays.asList("used", currentDate, currentUser)
                        
                );

                // 6. อัพเดทข้อมูลใน Google Sheets
                boolean updateSuccess = Login.sqs.updateData(
                        "room" + name + "!B" + rowToUpdate + ":D" + rowToUpdate,
                        usedData
                );

                if (updateSuccess) {
                    // 7. อัพเดท UI
                    updateButtonStatus(timeSlotIndex, currentUser);
                    JOptionPane.showMessageDialog(null,
                            "Reservation successful for " + getTimeSlotName(timeSlotIndex),
                            "Success",
                            JOptionPane.INFORMATION_MESSAGE);
                    try {
                Logger.getInstance().log(Login.currentUser, "RESERVE",Login.currentUser + " has reserved a room.");
                }
                catch (GeneralSecurityException | IOException ex) {
                    ex.printStackTrace();
                }
                } else {
                    JOptionPane.showMessageDialog(null,
                            "Failed to update reservation",
                            "Error",
                            JOptionPane.ERROR_MESSAGE);
                }
            } else {
                // แสดงข้อมูลการจองที่มีอยู่
                String bookedByUser = bookedBy.isEmpty() ? "unknown"
                        : bookedBy;
                JOptionPane.showMessageDialog(null,
                        "This time slot is already booked by: " + bookedByUser
                        + "\nBooking date: " + bookingDate,
                        "Already Booked",
                        JOptionPane.WARNING_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null,
                    "An error occurred: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

// เมธอดช่วยเหลือสำหรับอัพเดทสถานะปุ่ม
    private void updateButtonStatus(int timeSlotIndex, String bookedBy) {
        JButton button = getButtonByIndex(timeSlotIndex);
        if (button != null) {
            button.setBackground(new Color(249, 102, 102));
            button.setToolTipText("Booked by: " + bookedBy);
        }
    }

